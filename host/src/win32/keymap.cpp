uint32_t map_virtual_key(uint32_t code, uint32_t type) {
    constexpr uint32_t kVkToScan = 0;
    constexpr uint32_t kScanToVk = 1;
    constexpr uint32_t kVkToChar = 2;
    constexpr uint32_t kScanToVkEx = 3;
    for (const auto& k : kUsKeys) {
        switch (type) {
        case kVkToScan:
            if (k.vk == code) {
                return k.scan;
            }
            break;
        case kScanToVk:
        case kScanToVkEx:
            if (k.scan == code && (type == kScanToVkEx || k.vk < 0xa0)) {
                return k.vk;
            }
            break;
        case kVkToChar:
            if (k.vk == code) {
                return static_cast<uint8_t>(k.ch);
            }
            break;
        default:
            return 0;
        }
    }
    return 0;
}

